// Get all California cities (unique values)
function getCaliforniaCities() {
    const cities = [...new Set(Object.values(californiaZipCodes))];
    return cities.sort();
}

// Get zip codes for a specific city
function getZipCodesForCity(cityName) {
    const zipCodes = [];
    for (const [zip, city] of Object.entries(californiaZipCodes)) {
        if (city.toLowerCase() === cityName.toLowerCase()) {
            zipCodes.push(zip);
        }
    }
    return zipCodes.sort();
}

// Get city name for a zip code
function getCityByZipCode(zipCode) {
    return californiaZipCodes[zipCode] || null;
}

// Search zip codes by partial match
function searchZipCodes(query) {
    const matches = [];
    const queryLower = query.toLowerCase();
    
    for (const [zip, city] of Object.entries(californiaZipCodes)) {
        if (zip.startsWith(query) || city.toLowerCase().includes(queryLower)) {
            matches.push({ zip, city });
        }
    }
    
    return matches.sort((a, b) => {
        // Prioritize exact zip code matches
        if (a.zip.startsWith(query) && !b.zip.startsWith(query)) return -1;
        if (!a.zip.startsWith(query) && b.zip.startsWith(query)) return 1;
        
        // Then sort by city name
        return a.city.localeCompare(b.city);
    });
}

// Search cities by partial match
function searchCities(query) {
    const queryLower = query.toLowerCase();
    const cities = getCaliforniaCities();
    
    return cities.filter(city => 
        city.toLowerCase().includes(queryLower)
    ).sort();
}

